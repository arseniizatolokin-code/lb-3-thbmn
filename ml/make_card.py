"""Генерує картку моделі з реальних метрик: python ml/make_card.py"""
import json, os
H = os.path.dirname(__file__)
m = json.load(open(f"{H}/model/metrics.json")); meta = json.load(open(f"{H}/model/meta.json")); sp = json.load(open(f"{H}/data/split_report.json"))
n = meta["name"]; t = m["test"][n]; b = m["test"]["Базовий метод"]; ci = m["bootstrap_ci_95"][n]
txt = f"""# Картка моделі: оцінка ймовірності спору в угоді (тема 38)

**Версія (SHA-256 файлу `model.joblib`):** `{meta['sha256']}`
**Тип:** {n} (sklearn Pipeline: пропуски → медіана + індикатор пропуску, масштабування, one-hot для категорії)
**Гіперпараметри:** {meta['params']}; початкове значення генератора випадкових чисел: {meta['seed']}

## Призначення
Перед фінансуванням угоди оцінити ймовірність того, що вона закінчиться спором. Результат переводиться у базисні пункти й визначає розмір депозиту в контракті (від 2 % до 20 % суми). Модель **не** вирішує спір і **не** є підставою для відмови користувачеві.

## Дані
Синтетичний набір {sp['n_generated']} угод (симулятор `ml/simulator.py`, ЛР 1), період {sp['period'][0]} – {sp['period'][1]}. Розбиття за часом із карантином {sp['embargo_days']} днів:
train {sp['sizes']['train']}, val {sp['sizes']['val']}, test {sp['sizes']['test']} угод. Частка спорів: train {sp['dispute_rate']['train']:.1%}, val {sp['dispute_rate']['val']:.1%}, test {sp['dispute_rate']['test']:.1%}.
Реальних даних фріланс-бірж немає, тому абсолютні значення метрик не переносяться на реальні платформи.

## Метрики на тестовій вибірці (поріг {meta['threshold']:.3f}, підібраний на валідації)
| Метрика | {n} | Базовий метод (частка по категорії) |
|---|---|---|
| PR-AUC | {t['PR_AUC']:.3f} (95 % ДІ {ci['PR_AUC'][0]:.3f}–{ci['PR_AUC'][1]:.3f}) | {b['PR_AUC']:.3f} |
| ROC-AUC | {t['ROC_AUC']:.3f} (95 % ДІ {ci['ROC_AUC'][0]:.3f}–{ci['ROC_AUC'][1]:.3f}) | {b['ROC_AUC']:.3f} |
| F1 | {t['F1']:.3f} (95 % ДІ {ci['F1'][0]:.3f}–{ci['F1'][1]:.3f}) | {b['F1']:.3f} |
| Precision / Recall | {t['precision']:.3f} / {t['recall']:.3f} | {b['precision']:.3f} / {b['recall']:.3f} |
| Brier / ECE | {t['Brier']:.3f} / {t['ECE']:.3f} | {b['Brier']:.3f} / {b['ECE']:.3f} |

## Обмеження
- Навчено лише на синтетичних даних; на реальних даних якість потрібно перевіряти заново.
- Ясність ТЗ у сервісі оцінюється евристикою за кількістю слів, а не аналізом змісту тексту.
- Модель гірше виявляє спори замовників без історії спорів; приблизно 60 % спорів у тесті пропускаються за обраним порогом.
- Частка спорів у тесті вища, ніж у навчанні (дрейф): ймовірності можуть бути занижені.
- Файл моделі завантажується через joblib (pickle): використовувати лише файли з перевіреним хешем.

## Етичні застереження
Модель не використовує персональних даних: лише адреси, агреговані історії та параметри угоди. Рішення про депозит не повинно ставити в нерівні умови сторони за ознаками, не пов'язаними з угодою.
"""
open(f"{H}/model/model_card.md", "w", encoding="utf8").write(txt); print(txt[:400])
